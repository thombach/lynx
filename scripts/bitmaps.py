#!/usr/bin/env python3
"""Generates src/bitmap.h and src/bitmap.cpp from images/*.bmp (RGB565, black is transparent).

    python3 scripts/bitmaps.py          # Regenerate the sources
    python3 scripts/bitmaps.py --trim   # Also crop the blank borders of the images first
"""
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
IMAGES = ROOT / "images"
HEADER = ROOT / "src" / "bitmap.h"
SOURCE = ROOT / "src" / "bitmap.cpp"
VALUES_PER_LINE = 12


def to_rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def identifier(path):
    return "bitmap_" + re.sub(r"\W", "_", path.stem)


def trim(path):
    image = Image.open(path).convert("RGB")
    box = image.getbbox()  # Bounding box of the non-black pixels
    if box and box != (0, 0, *image.size):
        image.crop(box).save(path)
        print(f"Trimmed {path.name}: {image.size[0]}x{image.size[1]} -> {box[2] - box[0]}x{box[3] - box[1]}")


def definition(path):
    image = Image.open(path).convert("RGB")
    width, height = image.size
    if image.getbbox() != (0, 0, width, height):
        print(f"Warning: {path.name} has blank borders, run with --trim", file=sys.stderr)

    values = [f"0x{to_rgb565(*pixel):04x}" for pixel in image.getdata()]
    lines = [", ".join(values[i:i + VALUES_PER_LINE]) for i in range(0, len(values), VALUES_PER_LINE)]
    name = identifier(path)
    body = ",\n    ".join(lines)
    return (
        f"// '{path.stem}', {width}x{height}px\n"
        f"static const uint16_t {name}_pixels[] PROGMEM = {{\n    {body}}};\n"
        f"const Bitmap {name} = {{{name}_pixels, {width}, {height}}};\n"
    )


def main():
    paths = sorted(IMAGES.glob("*.bmp"))
    if "--trim" in sys.argv:
        for path in paths:
            trim(path)

    notice = "// Generated by scripts/bitmaps.py from images/*.bmp: edit the images, not this file\n"
    HEADER.write_text(
        "#pragma once\n" + notice + "#include <Arduino.h>\n\n"
        "struct Bitmap\n{\n"
        "    const uint16_t *pixels; // RGB565, black is transparent\n"
        "    int16_t width;\n"
        "    int16_t height;\n"
        "};\n\n"
        + "".join(f"extern const Bitmap {identifier(path)};\n" for path in paths)
    )
    SOURCE.write_text(notice + '#include "bitmap.h"\n\n' + "\n".join(definition(path) for path in paths))
    print(f"Wrote {len(paths)} bitmaps to {HEADER.relative_to(ROOT)} and {SOURCE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
